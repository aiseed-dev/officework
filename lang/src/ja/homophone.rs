//! 同音異義語の濾過器 — **指摘を出さない検査。**
//!
//! 1〜3 は指摘を出すが、これは**モデルへ送る量を減らす**のが仕事。
//! 誤変換(以外/意外)を判定するのはモデルのままで、辞書は
//! 「この文には紛らわしい語がある」と印を付けるだけ。
//!
//! # 英語との類比は、ここで切れる
//!
//! 英語の辞書は**語を全部知っている**ので「辞書に無い」は健全な濾過になる。
//! 落とした語は「大丈夫と証明できた」語である。
//!
//! **この表はそうではない。** 日本語の同音異義語は何万組もあり、
//! 数百組の表で落とせるのは「大丈夫と証明できた文」ではなく
//! **「表に載っていない文」**でしかない。だから
//! [`crate::check::Checker`] は**既定では濾過しない** — 明示で頼まれたときだけ
//! 濾過し、見ていない文の数を必ず `skipped` に残す(終了コード3)。
//!
//! # 効きの数字は、表が小さいほど良く見える
//!
//! 表に何を入れるかは**勘で決めない。** `tools/homophone_survey.py` が、
//! 実物の文書に**同じ読みの語が2つ以上そろって出ている**組を数えて出す。
//! 誤変換の入った文書は集められない(publish される前に直る)が、
//! **読みさえあれば「その書き手にとって紛らわしい語」は測れる。**
//!
//! # 効きの数字は、表が小さいほど良く見える
//!
//! **これは指標の罠なので、数を読むときは必ず表の大きさと一緒に読むこと。**
//! この repo の日本語文書(7,085文)で、表を無作為に間引いて実測した:
//!
//! ```text
//! 表の大きさ          送らずに済む
//!  18語                95.6%
//!  48語                95.2%
//!  96語                90.1%
//! 144語                86.0%
//! 193語                83.8%
//! 477語(いまの表)     63.6%   ← 表を26倍にして、数字はほぼ半分
//! ```
//!
//! 18語の表が「95.6% 落とせる」のは**ほとんど拾えていないから**であって、
//! 効いているからではない。そして**取りこぼし率は、正解の付いた文書が無いので
//! 測れない** — 上がる数字だけが測れて、下がる数字が測れない。
//! だから**「落とせた割合」を上げにいってはいけない。
//! 表を太らせる向きが正しく、数字が下がるのは正常。**

