/// 和語の語幹の後ろに立つ送り仮名の頭。
const OKURI_HEAD: &str = "るりろらっえけげせべめしいまつく";

/// 文の切れ目。
const BREAK: &str = "。！？!?\n";

/// 濾過の結果。
#[derive(Debug, Clone, PartialEq)]
pub struct Filtered {
    /// モデルへ渡す本文(紛らわしい語を含む文だけを繋いだ物)
    pub send: String,
    /// 送らなかった文の数。**これを黙ってはいけない**
    pub dropped: usize,
    /// 本文の文の数
    pub total: usize,
}

impl Filtered {
    /// 何も落としていないか。
    pub fn is_whole(&self) -> bool {
        self.dropped == 0
    }
}

/// 本文を文に割る。**切れ目の字は前の文に付ける**(位置がずれないように)。
///
/// 空白だけの塊は文として数えない。数えると、markdown の空行で分母が膨らんで
/// **効きが実際より良く見える**(実測で 83.7% が 87.0% に化けた)。
fn sentences(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    for c in text.chars() {
        cur.push(c);
        if BREAK.contains(c) {
            let s = std::mem::take(&mut cur);
            if !s.trim().is_empty() {
                out.push(s);
            }
        }
    }
    if !cur.trim().is_empty() {
        out.push(cur);
    }
    out
}

/// この文に紛らわしい語があるか。**あれば、その語を返す。**
pub fn marked(sentence: &str) -> Option<String> {
    for group in KANGO {
        for w in *group {
            if sentence.contains(w) {
                return Some((*w).to_string());
            }
        }
    }
    let ch: Vec<char> = sentence.chars().collect();
    for (i, c) in ch.iter().enumerate() {
        if WAGO.iter().any(|g| g.contains(c))
            && ch.get(i + 1).is_some_and(|n| OKURI_HEAD.contains(*n))
        {
            return Some(ch[i..=i + 1].iter().collect());
        }
    }
    None
}

/// 紛らわしい語を含む文だけを残す。
///
/// **落とした文は「大丈夫」ではなく「表に載っていない」だけ。**
/// 呼び出し側は [`Filtered::dropped`] を必ず利用者に伝えること。
pub fn filter(text: &str) -> Filtered {
    let all = sentences(text);
    let total = all.len();
    let mut send = String::new();
    let mut kept = 0;
    for s in &all {
        if marked(s).is_some() {
            send.push_str(s);
            kept += 1;
        }
    }
    Filtered { send, dropped: total - kept, total }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 紛らわしい語のある文だけ残す() {
        let f = filter("今日は晴れです。それは以外な結果でした。犬が走る。");
        assert_eq!(f.total, 3);
        assert_eq!(f.dropped, 2);
        assert!(f.send.contains("以外"), "{:?}", f.send);
        assert!(!f.send.contains("晴れ"), "{:?}", f.send);
    }

    #[test]
    fn 和語は送り仮名が続くときだけ語と見る() {
        // 「図る」は紛らわしい(計る/測る/量る)
        assert_eq!(marked("改善を図る。").as_deref(), Some("図る"));
        // 「図」だけなら熟語(地図・図面)。語ではないので印を付けない
        assert!(marked("地図の縮尺。").is_none());
        assert!(marked("図面の寸法。").is_none());
    }

    #[test]
    fn 漢語は熟語のまま拾う() {
        assert_eq!(marked("保証書を付ける。").as_deref(), Some("保証"));
        assert_eq!(marked("それは意外だ。").as_deref(), Some("意外"));
        assert!(marked("普通の文章です。").is_none());
    }

    #[test]
    fn 何も落とさないこともある() {
        let f = filter("以外な結果。意外な結果。");
        assert!(f.is_whole(), "{f:?}");
        assert_eq!(f.dropped, 0);
    }

    #[test]
    fn 全部落ちることもある() {
        let f = filter("犬が走る。猫が寝る。");
        assert_eq!(f.dropped, 2);
        assert!(f.send.is_empty());
    }

    #[test]
    fn 切れ目の字は前の文に付く() {
        // 落とした文の位置がずれないように
        let s = sentences("あ。い！う");
        assert_eq!(s, vec!["あ。", "い！", "う"]);
    }

    #[test]
    fn 空白だけの塊は文として数えない() {
        // 数えると markdown の空行で分母が膨らみ、効きが実際より良く見える
        let f = filter("以外な結果。\n\n\n犬が走る。");
        assert_eq!(f.total, 2, "空行を文に数えた: {f:?}");
        assert_eq!(f.dropped, 1);
    }

    #[test]
    fn 壊れた入力でも落ちない() {
        for s in ["", "。", "\n\n", "以外", "図"] {
            let _ = filter(s);
        }
    }

    #[test]
    fn 表に重なりがない() {
        // 同じ語を2つの組に書くと、どちらの組か分からなくなる
        let mut seen = std::collections::BTreeSet::new();
        for g in KANGO {
            for w in *g {
                assert!(seen.insert(*w), "漢語の表に重複: {w}");
            }
        }
        let mut c = std::collections::BTreeSet::new();
        for g in WAGO {
            for w in *g {
                assert!(c.insert(*w), "和語の表に重複: {w}");
            }
        }
    }
}
