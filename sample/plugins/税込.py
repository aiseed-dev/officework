"""消費税の計算 — officework の見本(セルの関数)

**置き場**: このファイルを `~/.config/office/plugins/` にコピーすると、
calc のセルから呼べるようになります(calc を開き直してください)。

    =税込(1000)          → 1100
    =税込(A1)            → セルの値に
    =税込(A1, 8)         → 軽減税率で
    =税抜(1100)          → 1000(逆算)
    =合計(A1:A10)        → 範囲をまとめて(表のまま渡せます)

**追加のライブラリは要りません。** `def` を書けばそれが関数の名前になり、
**日本語の名前もそのまま**使えます(`@xw.func` のような印は不要)。

セルの関数は**網に出ません**(囲いの中で通信を切って走ります)。外から
取ってくる仕事は手続きの持ち場です — 同じ場所の `天気.py` を見てください。
"""


def 税込(金額, 率=10):
    """税を足して円に丸める(既定は 10%)"""
    return round(float(金額) * (1 + float(率) / 100))


def 税抜(税込金額, 率=10):
    """税込みから税抜きを逆算する"""
    return round(float(税込金額) / (1 + float(率) / 100))


def 税額(金額, 率=10):
    """税のぶんだけ"""
    return 税込(金額, 率) - round(float(金額))


def 合計(*値):
    """数を足す。範囲(A1:A10)もそのまま渡せます。

    範囲は表(行の並び)で届くので、平らにしてから足します。
    数でないもの(見出しの文字など)は飛ばします。
    """
    def 平ら(x):
        if isinstance(x, (list, tuple)):
            for y in x:
                yield from 平ら(y)
        else:
            yield x

    合 = 0.0
    for v in 平ら(値):
        try:
            合 += float(v)
        except (TypeError, ValueError):
            continue  # 文字は飛ばす(見出しの入った範囲でも落ちない)
    return 合
