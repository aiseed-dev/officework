"""天気予報を表に取り込む — officework の見本(手続き)

**置き場**: このファイルを `~/.config/office/plugins/` にコピーすると、
calc から呼べるようになります(calc を開き直してください)。

    @天気              いまのセルから、東京の7日ぶんを書き込む
    @天気.大阪         大阪で
    @天気.週間         14日ぶん

出どころは [Open-Meteo](https://open-meteo.com/)(鍵の要らない天気の API)。
**追加のライブラリは要りません** — Python の標準の物だけで動きます。

## なぜセルの関数(=天気())ではなく手続きなのか

**セルの関数は網に出しません**(発注者確定 2026-08-14)。計算のたびに
外へ出ることになり、ブックを開いた瞬間に意図しない通信が起きるためです。
うちのセルの関数は囲いの中で網を切って走ります — 表計算の関数は
「入れた値から答えを出す」物であって、外へ取りに行く物ではない、が筋です。

外から取ってくる仕事は**手続き**(`@天気`)の持ち場です。押した時だけ走り、
結果を表として置きます。置いた後はただの値なので、開き直しても勝手に
通信しません。この分け方は xlwings の記事
(https://qiita.com/yniji/items/b38bc312e860027108ac)の「UDF は計算・
マクロは仕事」の分け方と同じ形です。
"""

import json
import urllib.request

from officework import calc as xw

# 都市 → (緯度, 経度)。ここに無い場所は 緯度と経度 を直に渡せます
都市 = {
    "東京": (35.68, 139.68),
    "横浜": (35.44, 139.64),
    "大阪": (34.69, 135.50),
    "名古屋": (35.18, 136.91),
    "札幌": (43.06, 141.35),
    "福岡": (33.59, 130.40),
    "神戸": (34.69, 135.20),
    "京都": (35.01, 135.77),
    "広島": (34.39, 132.46),
    "仙台": (38.27, 140.87),
    "那覇": (26.21, 127.68),
}

# WMO の天気コード → 日本語。**出せない細かさは足さない** —
# 「霧雨(やや強い)」まで分けても帳票では読まないので、使う言葉に丸める
天気の名 = {
    0: "快晴", 1: "晴れ", 2: "薄曇り", 3: "曇り",
    45: "霧", 48: "霧(着氷)",
    51: "霧雨", 53: "霧雨", 55: "霧雨(強)",
    56: "霧雨(着氷)", 57: "霧雨(着氷・強)",
    61: "雨", 63: "雨", 65: "大雨",
    66: "雨(着氷)", 67: "雨(着氷・強)",
    71: "雪", 73: "雪", 75: "大雪", 77: "細雪",
    80: "にわか雨", 81: "にわか雨", 82: "激しいにわか雨",
    85: "にわか雪", 86: "にわか雪(強)",
    95: "雷雨", 96: "雷雨(雹)", 99: "雷雨(雹・強)",
}


def 取る(lat, lon, 日数):
    """Open-Meteo から取って、表(見出し + 行)にして返す"""
    url = (
        "https://api.open-meteo.com/v1/forecast"
        f"?latitude={lat}&longitude={lon}"
        "&daily=weather_code,temperature_2m_max,temperature_2m_min,"
        "precipitation_probability_max"
        f"&timezone=Asia%2FTokyo&forecast_days={日数}"
    )
    with urllib.request.urlopen(url, timeout=15) as r:
        d = json.load(r)["daily"]
    表 = [["日付", "天気", "最高", "最低", "降水確率"]]
    for i, 日 in enumerate(d["time"]):
        code = d["weather_code"][i]
        表.append([
            日,
            天気の名.get(code, f"コード{code}"),
            d["temperature_2m_max"][i],
            d["temperature_2m_min"][i],
            d["precipitation_probability_max"][i],
        ])
    return 表


def 書く(場所="東京", 日数=7):
    """予報を取って、いま選んでいるセルから書き込む。

    **動いている calc をそのまま操ります**(ファイルの複製ではありません)。
    何行書いても Ctrl+Z 一回で戻せます。
    """
    if 場所 not in 都市:
        # **黙って東京にしない。** 知らない名前は名指しで断る
        raise SystemExit(f"知らない場所です: {場所}(使えるのは {'・'.join(都市)})")
    lat, lon = 都市[場所]
    表 = 取る(lat, lon, 日数)

    b = xw.Book.attach()          # いま開いている calc に繋ぐ
    先 = b.selection               # いま選んでいる範囲(Range)
    先.value = 表                  # 表のまま置く(右下へ広がる)
    print(f"{場所} の {日数} 日ぶんを {先.address} から書きました")


# ---- 呼び出しの入り口(@天気.〜 で呼ぶ名前) --------------------------------

def 東京():
    書く("東京")


def 大阪():
    書く("大阪")


def 札幌():
    書く("札幌")


def 福岡():
    書く("福岡")


def 那覇():
    書く("那覇")


def 週間():
    """14日ぶん(長めの予報)"""
    書く("東京", 14)


# `@天気` と module だけで呼んだ時に走る物
def main():
    書く()
