#!/usr/bin/env python3
"""Write the built-in table styles as book/src/table_styles.txt.

    python3 tools/gen_table_styles.py [OfficeOpenXML-SpreadsheetMLStyles.zip]

The source is presetTableStyles.xml in the SpreadsheetML styles package that
comes with ECMA-376 (default: ~/Documents/officework-cmp/ecma376/). Only the
table styles are written (TableStyleLight1 to Dark11), not the PivotTable
ones. Their dxfId counts from 1 (every one of them: no 0, and the largest is
the number of dxfs).

One line per table style element:

    style type size fill font bold top bottom left right vertical horizontal

A colour is `theme[:tint]` (all preset colours are theme colours), a border
`line:theme[:tint]`, and `-` means the element says nothing of it.
"""
import os
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Documents/officework-cmp/ecma376/OfficeOpenXML-SpreadsheetMLStyles.zip"
OUT = Path(__file__).resolve().parent.parent / "book/src/table_styles.txt"


def colour(e):
    if e is None:
        return "-"
    if e.get("theme") is None:
        raise SystemExit(f"not a theme colour: {e.attrib}")
    t = e.get("tint")
    return e.get("theme") + (f":{float(t):.6g}" if t and abs(float(t)) > 1e-9 else "")


def main():
    raw = zipfile.ZipFile(SRC).read("presetTableStyles.xml").decode("utf-8-sig")
    root = ET.fromstring(raw)
    lines = ["# Generated by tools/gen_table_styles.py from ECMA-376's presetTableStyles.xml. Do not edit."]
    for st in root:
        if not st.tag.startswith("TableStyle"):
            continue
        dxfs = list(st.find("dxfs"))
        for el in st.iter("tableStyleElement"):
            d = dxfs[int(el.get("dxfId")) - 1]
            fill = d.find("fill/patternFill")
            fill_c = "-"
            if fill is not None and fill.get("patternType", "solid") == "solid":
                fill_c = colour(fill.find("bgColor") if fill.find("bgColor") is not None else fill.find("fgColor"))
            font = d.find("font")
            font_c = colour(font.find("color")) if font is not None else "-"
            bold = "b" if font is not None and font.find("b") is not None else "-"
            sides = []
            for side in ("top", "bottom", "left", "right", "vertical", "horizontal"):
                b = d.find(f"border/{side}")
                if b is None or b.get("style") is None:
                    sides.append("-")
                else:
                    sides.append(f"{b.get('style')}:{colour(b.find('color'))}")
            lines.append(" ".join([st.tag, el.get("type"), el.get("size", "1"), fill_c, font_c, bold] + sides))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines) - 1} elements -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
