#!/usr/bin/env python3
"""**古めかしい言い方**が文書に残っていないか調べます。

2026-08-08 から4回、発注者から同じ指摘を受けています。禁止する言葉の表を
作っても、書くたびに新しい比喩を思いついてしまうので、機械に見てもらいます。

    python3 tools/kotoba_check.py

見るのは**利用者が読む文書**です。設計の記録(docs/sekkei/)と機能の対応表は
経緯を残す場所なので見ません。過去に書いたものまで直すと、記録が読めなく
なるためです。

判定に迷う言葉(「目的」の「的」、「便利」の「便」など)は、間違って
拾わないように、はっきりした形だけを見ます。**黙って見逃すほうが、
関係ない所で騒ぐより害が少ない**からです。
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# 見る文書。利用者が読むものだけ
TARGETS = [
    "README.adoc", "README.ja.adoc", "CLAUDE.md",
    "docs/*manual*.adoc", "docs/from-excel*.adoc", "docs/engine*.adoc",
    "docs/mac-signing.ja.adoc", "packaging/README.ja.md", "pysheet/README.md",
    "sample/README.md",
    # 引く1枚と、コマンドごとの手引き(2026-08-24 に足した)
    "docs/api-taiou.ja.adoc", "docs/genkou-manual.ja.adoc",
    "docs/docx-xlsx-tono-chigai.ja.adoc",
    "docs/commands/*.adoc", "docs/commands/*/*.adoc",
]

# 見ないもの(経緯を残す場所)
SKIP = ("docs/sekkei/", "guide-tsukiawase", ".flatpak-builder/")

# はっきり言い換えられる言葉。正規表現 → 言い換え
WORDS = [
    (r"台本", "スクリプト"),
    (r"門番", "チェック、検査"),
    (r"物差し", "基準、確認方法"),
    (r"巻物", "連続表示"),
    (r"組み手|折り手", "レイアウト処理"),
    (r"名乗り", "宣言"),
    (r"束縛", "変数"),
    (r"語彙", "書き方"),
    (r"正本", "元、原本"),
    (r"素の", "普通の、元の"),
    (r"着せ(る|ない|た)", "使う、使わない"),
    (r"実測", "実際に動かして確かめた"),
    (r"釦", "ボタン"),
    (r"檻", "サンドボックス"),
    (r"錨", "アンカー"),
    (r"生成器", "生成スクリプト"),
    # **仕事の分担を、場所の比喩で言わない**(2026-08-24 発注者
    # 「こういう表現はやめろ — 集計は Python(polars)の持ち場です。
    # 画面のボタンが裏で呼びます」)。Excel や Word のヘルプは
    # 「〜が処理します」「〜で行います」と書きます
    (r"持ち場", "受け持ち、担当、〜が処理する"),
    (r"裏方", "内部の処理、〜が処理する"),
    (r"裏で(呼|動|走)", "内部で呼ぶ、内部で動く"),
    (r"車線", "作業の流れ、別の作業"),
    (r"踏み跡", "分かったこと、経緯"),
    (r"家訓", "方針"),
    # **アプリを「殻」と呼ばない**(2026-08-19 発注者「殻の枠というような言葉は
    # つかうな」)。中身と外側を分けて言いたいときは「アプリ」「本体」で足ります
    (r"殻", "アプリ、本体"),
    # **タブを「耳」と呼ばない**(2026-08-19 発注者「下の耳のような日本の
    # プログラマーしか使わない言葉は使わないで」)。Excel のヘルプの言葉は
    # 「シート見出し」
    (r"耳", "タブ、シート見出し"),
    (r"泵", "(日本語ではない — 「30ms ごとに捌く」のように普通に書く)"),
    # **ボタンやタブに出る文字を「札」「名札」と呼ばない**
    # (2026-08-21 発注者「札のかぶりではなくて、ラベルの重複というように」)。
    # Excel と Word のヘルプは「ラベル」です。利用者が書く Python の
    # `リボン = {…}` のキーも、同じ日に「ラベル・アイコン・タブ」へ
    # 言い換えました(古いキーも読み続けます)
    (r"名?札", "ラベル、表示名"),
    # 同じ日の指摘。「かぶり」も普通の言葉ではありません
    (r"かぶり|札の重なり", "重複"),
    # **画面の周りを「額縁」と呼ばない**(2026-08-19 発注者「額縁では
    # なにかわからない」)。2026-08-04 に一度直したのに、設計文書から
    # 拾って戻っていた。**場所を指すときは具体に言う** —
    # 「画面の上の2行」「保存などのボタンの行」「リボンのタブの行」
    (r"額縁", "画面の組み立て(場所は「上の2行」のように具体に言う)"),
    # **画面の横長の部分を「帯」と呼ばない**(2026-08-19 発注者「帯という
    # 独自言語はつかうな」)。場面ごとに普通の名前があります —
    # リボンのボタンが並ぶ所は「リボン」、タブが並ぶ所は「タブの行」、
    # 表の見出しに色を敷くのは「見出し行の色」
    (r"帯(?!域)", "リボン、タブの行、見出し行の色(場面で使い分ける)"),
    # 入れ物の比喩。「器」「枠組み」は仕組みの名前として普通に言える
    (r"の器(?=[はをにがで、。\s])", "仕組み、入れ物"),
    # **設定やキーボードの「キー」を「鍵」と書かない**(2026-08-18 発注者)。
    # 暗号の鍵(公開鍵・秘密鍵・鍵ファイル)と、錠前の意味の「鍵ではありません」は
    # 普通の日本語なので拾わない
    (r"(?<!公開)(?<!秘密)(?<!署名の)(?<!打)鍵(?!ファイル)(?!ではありません)(?!束)(?!盤)", "キー"),
    # 形がはっきりしているものだけ拾う
    (r"別便|この便|次の便|同じ便", "回、作業"),
    (r"[のる]口(?=[はをにがで、。\s])", "API、ソケット、入り口"),
    (r"の的(?=[はをにがで、。\s])", "対象、対象 OS"),
    (r"を畳(む|んだ|んで)", "閉じる、削除する"),
]

# この文書自体は、言い換えの表を載せているので見逃します
ALLOW = {"CLAUDE.md", "tools/kotoba_check.py"}

# 語ごとの見逃し。**その文書では正しい日本語**なので拾いません
# (mac-signing は最初から最後まで署名の鍵の話です)
ALLOW_WORD = {"鍵": {"docs/mac-signing.ja.adoc"}}


def files():
    seen = []
    for pat in TARGETS:
        for p in sorted(ROOT.glob(pat)):
            rel = p.relative_to(ROOT).as_posix()
            if p.is_file() and rel not in ALLOW and not any(s in rel for s in SKIP):
                seen.append((rel, p))
    return seen


def main():
    hits = []
    for rel, p in files():
        for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            for pat, better in WORDS:
                m = re.search(pat, line)
                if m and rel in ALLOW_WORD.get(m.group(0), set()):
                    continue
                if m:
                    hits.append((rel, n, m.group(0), better, line.strip()[:60]))
    if hits:
        print(f"古めかしい言い方が {len(hits)} 箇所あります。")
        print("普通の言葉に直してください(CLAUDE.md の表)。\n")
        for rel, n, word, better, line in hits:
            print(f"  {rel}:{n}  「{word}」→ {better}")
            print(f"      {line}")
        return 1
    print(f"文書 {len(files())} 枚、古めかしい言い方はありません")
    return 0


if __name__ == "__main__":
    sys.exit(main())
